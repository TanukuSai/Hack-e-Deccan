# ==============================================================================

@pytest.mark.asyncio
async def test_gdpr_account_deletion_workflow():
    """
    Validates full GDPR account deletion:
    1. DELETE /api/v1/users/me
    2. Cascades to tenant relational entities (meetings, contacts, preferences)
    3. Anonymizes audit events (user_id = NULL with pseudonymized SHA-256 hash)
    4. Purges user profile completely
    """
    user_id = str(uuid.uuid4())
    await seed_user(user_id)

    # Populate child records for this tenant
    async with get_tenant_session(user_id) as session:
        # Create meeting
        m_res = await session.execute(
            text("""
            INSERT INTO public.meetings (user_id, title, start_time, end_time)
            VALUES (:u_id, 'GDPR Test Meeting', NOW(), NOW() + INTERVAL '1 hour')
            RETURNING id;
            """),
            {"u_id": user_id}
        )
        meeting_id = m_res.scalar()

        # Create audit event
        await session.execute(
            text("""
            INSERT INTO public.audit_events (
                user_id, original_user_hash, event_type, resource_type, resource_id
            )
            VALUES (
                :u_id, 'pending_hash', 'user_login', 'user_profile', :u_id
            );
            """),
            {"u_id": user_id}
        )

    token = create_access_token({"sub": user_id, "role": "authenticated"})
    headers = {"Authorization": f"Bearer {token}"}

    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        # Execute GDPR Account Deletion
        del_resp = await client.delete("/api/v1/users/me", headers=headers)
        assert del_resp.status_code == 204

    # Verify PostgreSQL database state
    async with engine.connect() as conn:
        # 1. Profile must be completely deleted
        prof = (await conn.execute(
            text("SELECT id FROM public.user_profiles WHERE id = :u_id;"),
            {"u_id": user_id}
        )).scalar()
        assert prof is None

        # 2. Cascaded child records must be gone
        meet = (await conn.execute(
            text("SELECT id FROM public.meetings WHERE user_id = :u_id;"),
            {"u_id": user_id}
        )).scalar()
        assert meet is None

        # 3. Audit events survive with user_id NULL and anonymized hash
        audit_row = (await conn.execute(
            text("SELECT user_id, original_user_hash FROM public.audit_events WHERE resource_id = :u_id;"),
            {"u_id": user_id}
        )).mappings().first()
        assert audit_row is not None
        assert audit_row["user_id"] is None
        assert audit_row["original_user_hash"] != "pending_hash"
        assert len(audit_row["original_user_hash"]) == 64  # SHA-256


