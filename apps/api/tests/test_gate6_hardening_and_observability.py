@pytest.mark.asyncio
async def test_openclaw_meeting_reconnaissance_adapter():
    """
    Validates OpenClaw adapter autonomous extraction of company background and attendee intelligence.
    Enforces strict security boundary: intelligence is tagged as unverified_assumption.
    """
    adapter = OpenClawAdapter(enabled=False) # Tests deterministic containment
    recon = await adapter.extract_meeting_recon(
        meeting_title="Enterprise Cloud Security Review",
        attendee_names=["David Miller"],
        company_domains=["cloudflare.com"]
    )
    assert recon["source"] == "openclaw_recon"
    assert recon["epistemic_class"] == "unverified_assumption"
    assert recon["verified"] is False
    assert "company_intelligence" in recon
    assert recon["company_intelligence"]["domain"] == "cloudflare.com"
    assert len(recon["attendee_recon"]) == 1
    assert recon["attendee_recon"][0]["name"] == "David Miller"
