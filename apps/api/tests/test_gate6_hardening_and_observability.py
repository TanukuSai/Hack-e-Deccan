# 4. Google OAuth 2.0 Integration Endpoints
# ==============================================================================

@pytest.mark.asyncio
async def test_google_oauth_integration_lifecycle():
    """
    Validates Google OAuth authorization URL generation, status inspection, and disconnect.
    """
    user_id = str(uuid.uuid4())
    await seed_user(user_id)
    token = create_access_token({"sub": user_id, "role": "authenticated"})
    headers = {"Authorization": f"Bearer {token}"}

    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        # 1. Get Google OAuth consent URL
        auth_url_resp = await client.get(
            "/api/v1/integrations/google/auth-url",
            params={"redirect_uri": "http://localhost:3000/auth/callback/google"},
            headers=headers
        )
        assert auth_url_resp.status_code == 200
        auth_data = auth_url_resp.json()
        assert "accounts.google.com" in auth_data["authorization_url"]
        assert "calendar.readonly" in auth_data["authorization_url"]
        assert "documents.readonly" in auth_data["authorization_url"]

        # 2. Check integration status (disconnected initially)
        status_resp = await client.get("/api/v1/integrations/google/status", headers=headers)
        assert status_resp.status_code == 200
        assert status_resp.json()["status"] == "disconnected"

        # 3. Disconnect endpoint
        disc_resp = await client.post("/api/v1/integrations/google/disconnect", headers=headers)
        assert disc_resp.status_code == 200
        assert disc_resp.json()["status"] == "disconnected"


