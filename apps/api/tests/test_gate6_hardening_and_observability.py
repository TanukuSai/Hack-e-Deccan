@pytest.mark.asyncio
async def test_correlation_id_and_observability_middleware():
    """
    Validates that every HTTP response carries a correlation ID and latency header.
    """
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        # Request without incoming ID -> autogenerated
        resp = await client.get("/health/live")
        assert resp.status_code == 200
        assert "x-request-id" in resp.headers
        assert "x-response-time-ms" in resp.headers

        # Request with client supplied ID -> echoed back
        custom_id = f"client-req-{uuid.uuid4().hex[:8]}"
        resp_custom = await client.get("/health/live", headers={"X-Request-ID": custom_id})
        assert resp_custom.headers["x-request-id"] == custom_id


