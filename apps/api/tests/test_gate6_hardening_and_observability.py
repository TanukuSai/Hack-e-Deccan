# ==============================================================================

@pytest.mark.asyncio
async def test_hard_spend_limit_enforcement_drill():
    """
    Drill: Proves that when user spend reaches the monthly budget ($25.00),
    CostService strictly blocks any further LLM reservations with BudgetExceededException.
    """
    user_id = str(uuid.uuid4())
    # User has spent $25.00 of their $25.00 monthly budget
    await seed_user(user_id, budget=25.0, spend=25.0)

    # Attempting to reserve even $0.001 must raise BudgetExceededException immediately
    with pytest.raises(BudgetExceededException):
        await CostService.reserve_budget(
            user_id=user_id,
            estimated_cost=Decimal("0.0050"),
            operation_type="outcome_proposal"
        )

    # Verify status reports hard_stop
    status_info = await CostService.get_budget_status(user_id)
    assert status_info["status"] == "hard_stop"
    assert status_info["percentage_used"] >= 100.0


